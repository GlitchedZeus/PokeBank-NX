#!/usr/bin/env python3
"""Generate include/Integration/Gen6/Gen6BagCatalog.h from pinned PKHeX sources.

Usage: gen_gen6_bag_catalog.py <ItemStorage6XY.cs> <ItemStorage6AO.cs> > include/Integration/Gen6/Gen6BagCatalog.h

Inputs: PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722
PKHeX.Core/Items/ItemStorage6XY.cs and ItemStorage6AO.cs. Each named
`ReadOnlySpan<ushort> Name => [ ... ];` list is copied in order; commented-out
entries ("// Illegal") are dropped exactly as the C# compiler drops them.
ItemStorage6AO reuses XY's Berry and Unreleased lists (`using static ItemStorage6XY`).
"""
import re
import sys


def lists(path):
    text = open(path, encoding="utf-8").read()
    text = re.sub(r"//[^\n]*", "", text)  # comments are not list members
    out = {}
    for name, body in re.findall(r"ReadOnlySpan<ushort>\s+(\w+)\s*=>\s*\[(.*?)\];", text, re.S):
        out[name] = [int(v) for v in re.findall(r"\d+", body)]
    return out


def emit(name, values):
    lines = ["inline constexpr std::array<uint16_t, %d> %s{{" % (len(values), name)]
    for i in range(0, len(values), 12):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + 12]) + ",")
    lines.append("}};")
    return "\n".join(lines)


def main():
    xy = lists(sys.argv[1])
    ao = lists(sys.argv[2])
    tables = [
        ("kGeneralXY", xy["General"]), ("kKeyXY", xy["Key"]), ("kMachineXY", xy["Machine"]),
        ("kMedicineXY", xy["Medicine"]), ("kBerry", xy["Berry"]), ("kUnreleased", xy["Unreleased"]),
        ("kGeneralAO", ao["General"]), ("kKeyAO", ao["Key"]), ("kMachineAO", ao["Machine"]),
        ("kMedicineAO", ao["Medicine"]),
    ]
    sys.stdout.write("""#ifndef POKEBANK_GEN6_BAG_CATALOG_H
#define POKEBANK_GEN6_BAG_CATALOG_H

// GENERATED by docs/gen6/tools/gen_gen6_bag_catalog.py -- do not edit by hand.
// Source: PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722
//   PKHeX.Core/Items/ItemStorage6XY.cs, ItemStorage6AO.cs (pouch item-ID lists, in order;
//   ORAS reuses the XY Berry and Unreleased lists). Native pouch member lists only:
//   NOT a story/ownership legality check.
#include <array>
#include <cstdint>

namespace PokeVault::Integration::Gen6::BagCatalog {

""")
    sys.stdout.write("\n\n".join(emit(n, v) for n, v in tables))
    sys.stdout.write("""

} // namespace PokeVault::Integration::Gen6::BagCatalog

#endif
""")


if __name__ == "__main__":
    main()
