#!/usr/bin/env python3
"""Generate include/Integration/Gen6/Gen6PersonalData.h from PKHeX personal_ao.

Usage: gen_gen6_personal.py <path/to/personal_ao> > include/Integration/Gen6/Gen6PersonalData.h

Input: PKHeX.Core/Resources/byte/personal/personal_ao at the pinned commit
6501f0ab46e8f8ca048539dbaf8cae8cb104e722 (66080 bytes, git blob
5263c9cbeb92bd15f4d1b8a691e5391eb91aac7a). Row layout from
PKHeX.Core/PersonalInfo/Info/PersonalInfo6AO.cs (SIZE 0x50): base stats 0x00..0x05
(HP, Atk, Def, Spe, SpA, SpD), Gender 0x12, EXPGrowth 0x15, FormStatsIndex u16 0x1C,
FormCount 0x20. PK6.PersonalInfo uses PersonalTable.AO for every Gen VI save.
"""
import hashlib
import struct
import sys

ROW = 0x50
EXPECTED_BLOB = "5263c9cbeb92bd15f4d1b8a691e5391eb91aac7a"


def git_blob_sha(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def main():
    data = open(sys.argv[1], "rb").read()
    blob = git_blob_sha(data)
    if blob != EXPECTED_BLOB or len(data) % ROW:
        raise SystemExit("unexpected personal_ao input (blob %s, %d bytes)" % (blob, len(data)))
    rows = []
    for i in range(len(data) // ROW):
        r = data[i * ROW:(i + 1) * ROW]
        rows.append("{%d,%d,%d,%d,%d,%d,%d,%d,%d,%d}" % (
            r[0], r[1], r[2], r[3], r[4], r[5], r[0x12], r[0x15],
            struct.unpack_from("<H", r, 0x1C)[0], r[0x20]))
    out = sys.stdout
    out.write("""#ifndef POKEBANK_GEN6_PERSONAL_DATA_H
#define POKEBANK_GEN6_PERSONAL_DATA_H

// GENERATED by docs/gen6/tools/gen_gen6_personal.py -- do not edit by hand.
// Source: PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722
//   PKHeX.Core/Resources/byte/personal/personal_ao (git blob %s, %d rows of 0x50)
//   layout: PKHeX.Core/PersonalInfo/Info/PersonalInfo6AO.cs
// Rows 0..721 are species; FormStatsIndex + form - 1 selects a form row.
// Independently cross-checked against PKSM-Core aa22d7a4 personals/personal6 in tests.
#include <array>
#include <cstdint>

namespace PokeVault::Integration::Gen6 {

struct Personal6 {
    uint8_t hp, atk, def, spe, spa, spd;
    uint8_t genderRatio, growthRate;
    uint16_t formStatsIndex;
    uint8_t formCount;
};

inline constexpr std::array<Personal6, %d> PersonalAO{{
""" % (blob, len(rows), len(rows)))
    for i in range(0, len(rows), 4):
        out.write("    " + ", ".join(rows[i:i + 4]) + ",\n")
    out.write("""}};

} // namespace PokeVault::Integration::Gen6

#endif
""")


if __name__ == "__main__":
    main()
