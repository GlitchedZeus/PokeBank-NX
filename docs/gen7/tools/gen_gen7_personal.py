#!/usr/bin/env python3
"""Generate include/Integration/Gen7/Gen7PersonalData.h from PKHeX personal_uu.

Usage: gen_gen7_personal.py <path/to/personal_uu> > include/Integration/Gen7/Gen7PersonalData.h

Input: PKHeX.Core/Resources/byte/personal/personal_uu at the pinned commit
6501f0ab46e8f8ca048539dbaf8cae8cb104e722 (66080 bytes, git blob
3803c5242a0e021f18ec8219ec78faab3a16de82). Row layout from
PKHeX.Core/PersonalInfo/Info/PersonalInfo7.cs (SIZE 0x54): base stats 0x00..0x05
(HP, Atk, Def, Spe, SpA, SpD), Gender 0x12, EXPGrowth 0x15, FormStatsIndex u16 0x1C,
FormCount 0x20. PK7.PersonalInfo uses PersonalTable.USUM for every Gen VII (SM and USUM) save.
"""
import hashlib
import struct
import sys

ROW = 0x54
EXPECTED_BLOB = "3803c5242a0e021f18ec8219ec78faab3a16de82"


def git_blob_sha(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def main():
    data = open(sys.argv[1], "rb").read()
    blob = git_blob_sha(data)
    if blob != EXPECTED_BLOB or len(data) % ROW:
        raise SystemExit("unexpected personal_uu input (blob %s, %d bytes)" % (blob, len(data)))
    rows = []
    for i in range(len(data) // ROW):
        r = data[i * ROW:(i + 1) * ROW]
        rows.append("{%d,%d,%d,%d,%d,%d,%d,%d,%d,%d}" % (
            r[0], r[1], r[2], r[3], r[4], r[5], r[0x12], r[0x15],
            struct.unpack_from("<H", r, 0x1C)[0], r[0x20]))
    out = sys.stdout
    out.write("""#ifndef POKEBANK_GEN7_PERSONAL_DATA_H
#define POKEBANK_GEN7_PERSONAL_DATA_H

// GENERATED by docs/gen7/tools/gen_gen7_personal.py -- do not edit by hand.
// Source: PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722
//   PKHeX.Core/Resources/byte/personal/personal_uu (git blob %s, %d rows of 0x54)
//   layout: PKHeX.Core/PersonalInfo/Info/PersonalInfo7.cs
// Rows 0..807 are species; FormStatsIndex + form - 1 selects a form row.
// Independently cross-checked against PKSM-Core aa22d7a4 personals/personal7 in tests.
#include <array>
#include <cstdint>

namespace PokeVault::Integration::Gen7 {

struct Personal7 {
    uint8_t hp, atk, def, spe, spa, spd;
    uint8_t genderRatio, growthRate;
    uint16_t formStatsIndex;
    uint8_t formCount;
};

inline constexpr std::array<Personal7, %d> PersonalUSUM{{
""" % (blob, len(rows), len(rows)))
    for i in range(0, len(rows), 4):
        out.write("    " + ", ".join(rows[i:i + 4]) + ",\n")
    out.write("""}};

} // namespace PokeVault::Integration::Gen7

#endif
""")


if __name__ == "__main__":
    main()
