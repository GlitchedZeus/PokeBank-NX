#!/usr/bin/env python3
"""Generate include/Integration/Gen7/Gen7BagCatalog.h from pinned PKHeX sources.

Usage: gen_gen7_bag_catalog.py <ItemStorage7SM.cs> <ItemStorage7USUM.cs> > include/Integration/Gen7/Gen7BagCatalog.h

Inputs: PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722 PKHeX.Core/Items/ItemStorage7SM.cs and
ItemStorage7USUM.cs. Each `ReadOnlySpan<ushort> Name => [ ... ];` list is copied in
order with comments dropped (as the compiler does). ItemStorage7USUM reuses SM's
General, Machine, Medicine, Berry and Unreleased lists (`using static ItemStorage7SM`).
"""
import re
import sys


def lists(path):
    text = re.sub(r"//[^\n]*", "", open(path, encoding="utf-8").read())
    return {n: [int(v) for v in re.findall(r"\d+", b)]
            for n, b in re.findall(r"ReadOnlySpan<ushort>\s+(\w+)\s*=>\s*\[(.*?)\];", text, re.S)}


def emit(name, values):
    out = ["inline constexpr std::array<uint16_t, %d> %s{{" % (len(values), name)]
    for i in range(0, len(values), 12):
        out.append("    " + ", ".join(str(v) for v in values[i:i + 12]) + ",")
    out.append("}};")
    return "\n".join(out)


def main():
    sm = lists(sys.argv[1])
    uu = lists(sys.argv[2])
    tables = [("kGeneral", sm["General"]), ("kMachine", sm["Machine"]), ("kMedicine", sm["Medicine"]),
              ("kBerry", sm["Berry"]), ("kUnreleased", sm["Unreleased"]),
              ("kKeySM", sm["Key"]), ("kZCrystalSM", sm["ZCrystalKey"]),
              ("kKeyUSUM", uu["Key"]), ("kZCrystalUSUM", uu["ZCrystalKey"]), ("kRotoUSUM", uu["Roto"])]
    sys.stdout.write("""#ifndef POKEBANK_GEN7_BAG_CATALOG_H
#define POKEBANK_GEN7_BAG_CATALOG_H

// GENERATED by docs/gen7/tools/gen_gen7_bag_catalog.py -- do not edit by hand.
// Source: PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722
//   PKHeX.Core/Items/ItemStorage7SM.cs, ItemStorage7USUM.cs (USUM reuses SM's General,
//   Machine, Medicine, Berry and Unreleased). Native pouch member lists only:
//   NOT a story/ownership legality check.
#include <array>
#include <cstdint>

namespace PokeVault::Integration::Gen7::BagCatalog {

""")
    sys.stdout.write("\n\n".join(emit(n, v) for n, v in tables))
    sys.stdout.write("""

} // namespace PokeVault::Integration::Gen7::BagCatalog

#endif
""")


if __name__ == "__main__":
    main()
