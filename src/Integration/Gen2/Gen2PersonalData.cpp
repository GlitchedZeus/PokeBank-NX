const PersonalRecord* personalRecord(uint16_t species) noexcept {
    if (species == 0 || species >= kPersonal.size()) return nullptr;
    return &kPersonal[species];
}

PokemonGender genderFromAttackDV(uint16_t species, uint8_t attackDV) noexcept {
    const PersonalRecord* p = personalRecord(species);
    if (!p || attackDV > 15) return PokemonGender::Unknown;

    switch (p->genderRatio) {
        case 0: return PokemonGender::Male;
        case 254: return PokemonGender::Female;
        case 255: return PokemonGender::Genderless;
        default:
            return attackDV > (p->genderRatio >> 4)
                ? PokemonGender::Male : PokemonGender::Female;
    }
}

