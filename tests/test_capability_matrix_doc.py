#!/usr/bin/env python3
"""docs/gen6-plus/CAPABILITY_MATRIX.md must be exactly what tools/capability_matrix.cpp prints.

This script builds nothing. It runs the already-built generator (--binary, default
build-host/capability_matrix, as Makefile.host.capability-matrix builds it), compares the committed
document byte for byte with the generator's stdout, and checks the document's shape:

  * 38 game rows across the per-generation tables;
  * a Game column followed by exactly the 12 capability columns, in the required order;
  * no empty cell;
  * every Gen VI-IX row's "Switch hardware verification" cell is NOT TESTED (no hardware claim can
    appear for a title the owner has not accepted on a Switch);
  * the fixed header vocabulary line and footer line.

Exit status 1 with a readable diff / message on any failure.
"""
from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "gen6-plus" / "CAPABILITY_MATRIX.md"
EXPECTED_ROWS = 38
COLUMNS = [
    "Dashboard/Save Instances",
    "Party/Boxes",
    "Pokemon editor",
    "Native mechanics",
    "Trainer",
    "Bag",
    "Pokedex",
    "Create/Clone/Move/Remove",
    "Backup/Review",
    "Export and safety",
    "CI",
    "Switch hardware verification",
]
HEADER_VOCABULARY = "PASS means host-tested through the shared workflow, never hardware acceptance"
FOOTER = "Generated by tools/capability_matrix.cpp from GameCapabilityRegistry.h; do not edit by hand."
ROMAN = {"I": 1, "II": 2, "III": 3, "IV": 4, "V": 5, "VI": 6, "VII": 7, "VIII": 8, "IX": 9}
GENERATION_HEADING = re.compile(r"^## Generation ([IVX]+) \(")


def fail(message: str) -> None:
    sys.stderr.write(f"test_capability_matrix_doc: FAIL: {message}\n")
    raise SystemExit(1)


def split_row(line: str) -> list[str]:
    body = line.strip()
    if not (body.startswith("|") and body.endswith("|")):
        fail(f"malformed table row: {line!r}")
    # Cells never contain an unescaped pipe (the generator escapes them).
    return [cell.strip() for cell in re.split(r"(?<!\\)\|", body[1:-1])]


def check_shape(text: str) -> None:
    if HEADER_VOCABULARY not in text:
        fail("header vocabulary line is missing")
    lines = text.splitlines()
    if not lines or lines[-1] != FOOTER:
        fail("footer line is missing or is not the last line")

    generation = 0
    in_game_table = False
    rows = 0
    for number, line in enumerate(lines, start=1):
        heading = GENERATION_HEADING.match(line)
        if heading:
            generation = ROMAN[heading.group(1)]
            in_game_table = False
            continue
        if line.startswith("## "):
            generation = 0
            in_game_table = False
            continue
        if not line.startswith("|"):
            in_game_table = False
            continue
        cells = split_row(line)
        if cells[0] == "Game" and generation:
            if cells[1:] != COLUMNS:
                fail(f"line {number}: Generation table columns are {cells[1:]}, expected {COLUMNS}")
            in_game_table = True
            continue
        if not in_game_table:
            continue
        if all(set(c) <= {"-"} for c in cells):
            if len(cells) != len(COLUMNS) + 1:
                fail(f"line {number}: separator has {len(cells)} columns, expected {len(COLUMNS) + 1}")
            continue
        if len(cells) != len(COLUMNS) + 1:
            fail(f"line {number}: row has {len(cells)} columns, expected {len(COLUMNS) + 1}: {line}")
        for index, cell in enumerate(cells):
            if not cell:
                fail(f"line {number}: empty cell in column {index} ({'Game' if index == 0 else COLUMNS[index - 1]})")
        rows += 1
        hardware = cells[1 + COLUMNS.index("Switch hardware verification")]
        if generation >= 6 and hardware != "NOT TESTED":
            fail(f"line {number}: Generation {generation} row claims hardware status {hardware!r}; must be NOT TESTED")
        # No title is accepted on an exact build: Gen I-V owner rounds ran on earlier candidates
        # (issue #313 open), so the baseline rows must say NOT ACCEPTED, never OWNER ACCEPTED.
        if generation < 6 and not hardware.startswith("NOT ACCEPTED"):
            fail(f"line {number}: Generation {generation} baseline row has hardware status {hardware!r}")
        if hardware.startswith("OWNER ACCEPTED"):
            fail(f"line {number}: no exact-build owner acceptance exists; {hardware!r} is not allowed")
    if rows != EXPECTED_ROWS:
        fail(f"found {rows} game rows, expected {EXPECTED_ROWS}")
    if f"Rows: {EXPECTED_ROWS} titles." not in text:
        fail("row count line is missing or disagrees with the table")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--binary", default=str(ROOT / "build-host" / "capability_matrix"),
                        help="built generator (make -f Makefile.host <HOST_BUILD>/capability_matrix)")
    parser.add_argument("--doc", default=str(DOC), help="committed document to compare against")
    args = parser.parse_args()

    binary = Path(args.binary)
    if not binary.is_file():
        fail(f"generator not built: {binary} (build it with make -f Makefile.host {binary})")
    doc = Path(args.doc)
    if not doc.is_file():
        fail(f"committed document missing: {doc} (make -f Makefile.host capability-matrix-doc)")

    run = subprocess.run([str(binary)], capture_output=True, check=False)
    if run.returncode != 0:
        fail(f"generator exited {run.returncode}: {run.stderr.decode('utf-8', 'replace').strip()}")
    generated = run.stdout
    committed = doc.read_bytes()
    if generated != committed:
        diff = difflib.unified_diff(
            committed.decode("utf-8", "replace").splitlines(keepends=True),
            generated.decode("utf-8", "replace").splitlines(keepends=True),
            fromfile=str(doc) + " (committed)",
            tofile=str(binary) + " (generated)",
        )
        sys.stderr.write("".join(diff))
        fail("committed capability matrix differs from the registry; run make -f Makefile.host capability-matrix-doc")

    check_shape(generated.decode("utf-8"))
    print(f"test_capability_matrix_doc: PASS ({EXPECTED_ROWS} rows x {len(COLUMNS)} capability columns, byte-identical)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
