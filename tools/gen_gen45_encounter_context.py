#!/usr/bin/env python3
"""Reproduce species-level wild-location context, not a legality verdict.

Input is an unmodified PKHeX checkout at PIN. No ROM/save or network input is used.
Formats: BinLinkerAccessor[16], EncounterArea4/5 and EvolutionSet.GetMethod.
Slot, form, season, time, lead ability and evolution requirements are deliberately
not evaluated by this UI catalogue. Static/gift/event/egg histories remain unknown.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess

PIN = "6042efa241a9925ce57e645329ea7f976deabdd3"
GAMES = {4: {"d": "diamond_nds", "p": "pearl_nds", "pt": "platinum_nds",
             "hg": "heartgold_nds", "ss": "soulsilver_nds"},
         5: {"b": "black_nds", "w": "white_nds", "b2": "black2_nds", "w2": "white2_nds"}}
METHODS = {4: ("Grass", "Surf", "OldRod", "GoodRod", "SuperRod", "RockSmash",
               "Headbutt", "HeadbuttSpecial", "BugContest", "HoneyTree", "SafariGrass",
               "SafariSurf", "SafariOldRod", "SafariGoodRod", "SafariSuperRod"),
           5: ("Standard", "Grass", "Surf", "SuperRod", "Swarm", "HiddenGrotto")}


def entries(data, width):
    if len(data) < 4:
        raise ValueError("short BinLinker header")
    count = struct.unpack_from("<H", data, 2)[0]
    header = 4 + width * (count + 1)
    if header > len(data):
        raise ValueError("short BinLinker offset table")
    offsets = struct.unpack_from("<" + ("H" if width == 2 else "I") * (count + 1), data, 4)
    if offsets[0] < header or offsets[-1] != len(data) or any(a > b for a, b in zip(offsets, offsets[1:])):
        raise ValueError("invalid BinLinker offsets")
    return [data[a:b] for a, b in zip(offsets, offsets[1:])]


def generate(checkout):
    revision = subprocess.check_output(["git", "-C", str(checkout), "rev-parse", "HEAD"], text=True).strip()
    if revision != PIN:
        raise ValueError(f"expected primary source {PIN}, got {revision}")
    core = checkout / "PKHeX.Core"
    hashes = {}

    def read(rel):
        data = (core / rel).read_bytes()
        # Reject modified inputs even when the checkout's HEAD still matches.
        original = subprocess.check_output(["git", "-C", str(checkout), "show", f"{PIN}:PKHeX.Core/{rel}"])
        if data != original:
            raise ValueError(f"modified primary source: {rel}")
        hashes[rel] = hashlib.sha256(data).hexdigest()
        return data

    for rel in ("Legality/Assets/BinLinkerAccessor.cs", "Legality/Assets/BinLinkerAccessor16.cs",
                "Legality/Encounters/Templates/Gen4/EncounterArea4.cs",
                "Legality/Encounters/Templates/Gen5/EncounterArea5.cs",
                "Legality/Evolutions/EvolutionSet.cs", "Game/Locations/Locations.cs"):
        read(rel)
    rows, edges, counts = set(), set(), {}
    for gen, games in GAMES.items():
        maximum = 493 if gen == 4 else 649
        for short, game in games.items():
            raw = read(f"Resources/legality/wild/Gen{gen}/encounter_{short}.pkl")
            for area in entries(raw, 4):
                header, step = (6, 10) if gen == 4 else (4, 4)
                if len(area) < header or area[2] >= len(METHODS[gen]):
                    raise ValueError(f"invalid {game} area header")
                location = area[0] if gen == 4 else struct.unpack_from("<H", area)[0]
                for offset in range(header, len(area) - step + 1, step):
                    species = struct.unpack_from("<H", area, offset)[0]
                    if gen == 5:
                        species &= 0x3FF
                    low, high = area[offset + (4 if gen == 4 else 2):offset + (6 if gen == 4 else 4)]
                    if not any(area[offset:offset + step]):  # Empty slots, not evidence.
                        continue
                    if not (0 < species <= maximum and 0 < low <= high <= 100):
                        raise ValueError(f"invalid {game} species/level row")
                    rows.add((game, species, location, low, high, METHODS[gen][area[2]]))
            counts[game] = sum(row[0] == game for row in rows)
        raw = read(f"Resources/byte/evolve/evos_g{gen}.pkl")
        for parent, data in enumerate(entries(raw, 2)):
            if len(data) % 8:
                raise ValueError("invalid evolution entry size")
            for offset in range(0, len(data), 8):
                child = struct.unpack_from("<H", data, offset + 4)[0]
                if not (0 < parent <= maximum and 0 < child <= maximum):
                    raise ValueError("invalid evolution species")
                edges.add((gen, child, parent))
    text = ["// GENERATED by tools/gen_gen45_encounter_context.py; do not edit.",
            f"// PKHeX primary source: {PIN}",
            "// Species-level location context only. Forms/conditions are not checked.",
            "// Absence is UNKNOWN: eggs, gifts, static, trade, event and transfer histories remain possible.",
            "inline constexpr EncounterGuardrails::EncounterTemplate kWild45[] = {"]
    text += [f'    {{"{g}", {s}, {loc}, {lo}, {hi}, EncounterGuardrails::Method::{m}, 0}},'
             for g, s, loc, lo, hi, m in sorted(rows)]
    text += ["};", "inline constexpr EvolutionEdge kEvolution45[] = {"]
    text += [f"    {{{g}, {child}, {parent}}}," for g, child, parent in sorted(edges)]
    text += ["};", ""]
    manifest = {"source": "https://github.com/kwsch/PKHeX", "revision": PIN,
                "scope": "species-level wild locations and ancestry only; no legality verdict",
                "counts": counts, "evolution_edges": len(edges), "inputs_sha256": hashes}
    return "\n".join(text), json.dumps(manifest, indent=2, sort_keys=True) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkout", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    outputs = (root / "include/Integration/Encounter/EncounterContext45Data.inc",
               root / "docs/data/gen45-encounter-context-sources.json")
    for path, content in zip(outputs, generate(args.checkout)):
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"not reproducible: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("Gen IV/V encounter context: pinned source and generated data verified")
