#!/usr/bin/env python3
"""Generate include/Legality/GBBaseStats.inc: the base stats of species 1-251 for the Gen I/II
party stat rule (GBLegality.cpp partyStatProblems).

The values come from the pret disassemblies, independently of PKHeX and of the PKSM port
in Gen2PersonalData.cpp: pokecrystal data/pokemon/base_stats.asm (INCLUDE order, each file
naming its species and dex number) and, for 1-151, pokered data/pokemon/base_stats/*.asm.
HP, Attack, Defense and Speed did not change between the generations and must agree; the
Gen I Special is kept beside the Gen II Special Attack and Special Defense. With --pokeyellow,
Yellow's table must match Red/Blue's.

    tools/gen_gb_base_stats.py --pokered POKERED --pokecrystal POKECRYSTAL [--pokeyellow Y] [--check]
"""
import argparse
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "include/Legality/GBBaseStats.inc"
STATS = re.compile(r"^\s*db\s+(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*(\d+))?\s*$", re.M)


def crystal(root):
    order = re.findall(r'INCLUDE "(data/pokemon/base_stats/\w+\.asm)"', (root / "data/pokemon/base_stats.asm").read_text())
    stats = {}
    for dex, path in enumerate(order, 1):
        text = (root / path).read_text()
        number = re.search(r"^\s*db\s+\w+\s*;\s*(\d+)", text, re.M)
        if not number or int(number[1]) != dex:
            sys.exit(f"{path}: expected dex {dex}")
        stats[dex] = [int(v) for v in STATS.search(text).groups()]  # HP ATK DEF SPE SPA SPD
    if sorted(stats) != list(range(1, 252)):
        sys.exit("pokecrystal: expected species 1-251")
    return stats


def red(root):
    # constants/pokedex_constants.asm: const_def 1, then one "const DEX_X" per species.
    names = re.findall(r"^\s*const\s+(DEX_\w+)", (root / "constants/pokedex_constants.asm").read_text(), re.M)
    dex = {name: i for i, name in enumerate(names, 1)}
    stats = {}
    for path in (root / "data/pokemon/base_stats").glob("*.asm"):
        text = path.read_text()
        number = re.search(r"^\s*db\s+(DEX_\w+)", text, re.M)
        if number:
            stats[dex[number[1]]] = [int(v) for v in STATS.search(text).groups()[:5]]  # HP ATK DEF SPE SPC
    if sorted(stats) != list(range(1, 152)):
        sys.exit(f"{root}: expected species 1-151")
    return stats


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pokered", type=Path, required=True)
    ap.add_argument("--pokecrystal", type=Path, required=True)
    ap.add_argument("--pokeyellow", type=Path)
    ap.add_argument("--check", action="store_true", help="fail when the committed table differs")
    args = ap.parse_args()
    gsc, rby = crystal(args.pokecrystal), red(args.pokered)
    if args.pokeyellow and red(args.pokeyellow) != rby:
        sys.exit("pokeyellow base stats differ from pokered")
    for dex in range(1, 152):
        if gsc[dex][:4] != rby[dex][:4]:
            sys.exit(f"species {dex}: pokered HP/ATK/DEF/SPE {rby[dex][:4]} != pokecrystal {gsc[dex][:4]}")
    rows = ["{" + ", ".join(map(str, gsc[dex] + [rby[dex][4] if dex <= 151 else 0])) + "}," for dex in range(1, 252)]
    body = "// Generated by tools/gen_gb_base_stats.py from pret/pokered and pret/pokecrystal; do not edit.\n"
    body += "// Species 0-251: HP, Attack, Defense, Speed, Special Attack, Special Defense (Gen II),\n"
    body += "// Special (Gen I; 0 above 151). All zero for the empty species.\n"
    body += "{0, 0, 0, 0, 0, 0, 0},\n" + "".join(f"{row}  // {dex}\n" for dex, row in enumerate(rows, 1))
    if args.check:
        if OUT.read_text() != body:
            sys.exit(f"{OUT} is out of date; rerun tools/gen_gb_base_stats.py")
        print("GBBaseStats.inc matches pret")
    else:
        OUT.write_text(body)
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
