#!/usr/bin/env python3
"""Regenerate the Generation V (BW / B2W2) move picker table.

Sources (pinned):
  * PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722 PKHeX.Core/Moves/MoveInfo5.cs
    - authoritative Gen V base PP and move type (PKHeX type order).
  * Pokemon Showdown 3a766f2cfb5e51c1e428cfe87d0dba91a8f01640
    data/moves.ts with the data/mods/gen8 -> gen7 -> gen6 -> gen5 inheritance chain
    - Gen V power, accuracy and damage category.
The generator fails unless Showdown's Gen V PP and type agree with PKHeX for every
move 1..559, so neither source is trusted alone.
"""
from __future__ import annotations
import pathlib, re, urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "include" / "Names" / "MoveBattleStats5.h"
PKHEX = ("kwsch/PKHeX", "6501f0ab46e8f8ca048539dbaf8cae8cb104e722", "PKHeX.Core/Moves/MoveInfo5.cs")
SHOWDOWN = ("smogon/pokemon-showdown", "3a766f2cfb5e51c1e428cfe87d0dba91a8f01640")
SHOWDOWN_FILES = ["data/moves.ts", "data/mods/gen8/moves.ts", "data/mods/gen7/moves.ts",
                  "data/mods/gen6/moves.ts", "data/mods/gen5/moves.ts"]
TYPES = ["Normal", "Fighting", "Flying", "Poison", "Ground", "Rock", "Bug", "Ghost", "Steel",
         "Fire", "Water", "Grass", "Electric", "Psychic", "Ice", "Dragon", "Dark"]
CATEGORY = {"Physical": 0, "Special": 1, "Status": 2}
MAX_MOVE = 559
VARIABLE_TYPE = {237}  # Hidden Power
UNDEFINED = 255

def fetch(repo, ref, path):
    with urllib.request.urlopen(f"https://raw.githubusercontent.com/{repo}/{ref}/{path}") as r:
        return r.read().decode()

def pkhex_span(text, name):
    m = re.search(name + r"\s*=>\s*\[(.*?)\];", text, re.S)
    return [int(v) for v in re.findall(r"\d+", m.group(1))]

FIELD = re.compile(r'^\t\t(num|accuracy|basePower|category|type|pp): ("[^"]*"|\w+),$', re.M)

def showdown_entries(text):
    """Top-level `\tkey: {` ... `\t},` blocks; only direct (two-tab) fields."""
    out = {}
    for m in re.finditer(r'^\t"?([a-z0-9]+)"?: \{\n(.*?)^\t\},$', text, re.M | re.S):
        out[m.group(1)] = {k: v.strip('"') for k, v in FIELD.findall(m.group(2) + "\n")}
    return out

def main():
    mi5 = fetch(*PKHEX)
    pp5, type5 = pkhex_span(mi5, "PP"), pkhex_span(mi5, "Type")
    assert len(pp5) == MAX_MOVE + 1 and len(type5) == MAX_MOVE + 1
    merged = {}
    for path in SHOWDOWN_FILES:
        for key, fields in showdown_entries(fetch(*SHOWDOWN, path)).items():
            merged.setdefault(key, {}).update(fields)
    by_num = {}
    for fields in merged.values():
        if "num" in fields and 1 <= int(fields["num"]) <= MAX_MOVE:
            by_num[int(fields["num"])] = fields
    rows = [(0, 0, UNDEFINED, UNDEFINED, 0)]  # type, category, power, accuracy, pp
    for move in range(1, MAX_MOVE + 1):
        f = by_num[move]
        mtype, pp = type5[move], int(f["pp"])
        # Hidden Power's displayed type depends on IVs; PKHeX stores its base type.
        assert TYPES.index(f["type"]) == mtype or move in VARIABLE_TYPE, (move, f["type"], mtype)
        assert pp == pp5[move], (move, pp, pp5[move])
        # Hidden Power's power is IV-derived in Gen V (30..70), not a table constant.
        power = 0 if move in VARIABLE_TYPE else int(f["basePower"])
        accuracy = f["accuracy"]
        rows.append((mtype, CATEGORY[f["category"]], power if power > 0 else UNDEFINED,
                     UNDEFINED if accuracy == "true" else int(accuracy), pp))
    out = [
        "/**",
        " * MoveBattleStats5.h - Black/White and Black 2/White 2 move picker data.",
        " * AUTO-GENERATED by tools/gen_move_battle_stats5.py. DO NOT EDIT BY HAND.",
        f" * Type and base PP: PKHeX {PKHEX[1]} {PKHEX[2]}.",
        f" * Power / accuracy / category: Pokemon Showdown {SHOWDOWN[1]} data/moves.ts with",
        " * the gen8 -> gen7 -> gen6 -> gen5 mod chain; PP and type are cross-checked",
        " * against PKHeX for every move. 255 = undefined (variable power or a move",
        " * that never misses): shown as an em dash, never 0. Type uses the PKHeX order",
        " * (0 Normal .. 16 Dark). Move data only: says nothing about learnability.",
        " */",
        "#ifndef NAMES_MOVE_BATTLE_STATS5_H",
        "#define NAMES_MOVE_BATTLE_STATS5_H",
        "#include <array>",
        "#include <cstdint>",
        "namespace Names {",
        "struct MoveBattleStats5 { uint8_t type=0; uint8_t category=0; uint8_t power=255; uint8_t accuracy=255; uint8_t pp=0; };",
        "inline constexpr uint8_t kMoveValueUndefined5 = 255;",
        f"inline constexpr std::array<MoveBattleStats5, {len(rows)}> kMoveBattleStats5{{{{",
    ]
    for i in range(0, len(rows), 6):
        out.append("    " + " ".join("{%d,%d,%d,%d,%d}," % r for r in rows[i:i + 6]))
    out += [
        "}};",
        "inline const MoveBattleStats5* getMoveBattleStats5(uint16_t move) noexcept {",
        "    return move > 0 && move < kMoveBattleStats5.size() ? &kMoveBattleStats5[move] : nullptr;",
        "}",
        "inline const char* moveCategoryName5(uint8_t category) noexcept {",
        "    return category == 0 ? \"Physical\" : category == 1 ? \"Special\" : category == 2 ? \"Status\" : \"\";",
        "}",
        "} // namespace Names",
        "#endif",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")

if __name__ == "__main__":
    main()
