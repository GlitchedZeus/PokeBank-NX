#!/usr/bin/env python3
"""Rebuild pinned Emerald level-up evidence, without inferential move methods.

Usage:
  python3 tools/gen_legality_gen3_emerald_levelup.py
  python3 tools/gen_legality_gen3_emerald_levelup.py --check
  python3 tools/gen_legality_gen3_emerald_levelup.py --source-root /path/to/pokeemerald
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path
import re
from urllib.request import Request, urlopen

REV = "5eff78649e7170a877b961ef0b3da13b81a16038"
SOURCES = {
    "include/constants/pokedex.h": "c9c51623e5eba68363c059a339304a3388f07d1e",
    "include/constants/moves.h": "324bfb89962858ca21e58293d85c45f3bf3a6869",
    "src/data/pokemon/level_up_learnsets.h": "212b969a70e0dd454be2be71615f59496388bfb2",
    "src/data/pokemon/level_up_learnset_pointers.h": "661458ce383ef517cea82c637bfb99536b6f65c3",
}
OUT = Path(__file__).resolve().parents[1] / "include/Legality/Gen3EmeraldLevelUpData.inc"

def load(path: str, root: Path | None) -> str:
    if root is not None:
        data = (root / path).read_bytes()
    else:
        url = f"https://raw.githubusercontent.com/pret/pokeemerald/{REV}/{path}"
        with urlopen(Request(url, headers={"User-Agent": "PokeBank-NX-legality-data-generator"}), timeout=30) as response:
            data = response.read()
    git_sha = hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()
    if git_sha != SOURCES[path]:
        raise ValueError(f"Unexpected pinned source content for {path}: {git_sha}")
    return data.decode("utf-8")

def fmt(numbers: list[int]) -> str:
    return "".join(
        "    " + ", ".join(str(n) for n in numbers[i:i+12]) +
        ("," if i + 12 < len(numbers) else "") + "\n"
        for i in range(0, len(numbers), 12)
    )

def render(root: Path | None) -> str:
    dex, move_h, learn, ptr_h = (load(p, root) for p in SOURCES)
    national = re.findall(r"^\s*NATIONAL_DEX_([A-Z0-9_]+),\s*$",
                          dex.split("NATIONAL_DEX_OLD_UNOWN_B", 1)[0], re.M)
    if len(national) != 387 or national[0] != "NONE" or national[-1] != "DEOXYS":
        raise ValueError("National Dex order is incomplete")
    move_ids = {name: int(value) for name, value in re.findall(
        r"^#define MOVE_([A-Z0-9_]+) (\d+)\s*$", move_h, re.M)}
    pointers = dict(re.findall(
        r"\[SPECIES_([A-Z0-9_]+)\]\s*=\s*s([A-Za-z0-9]+)LevelUpLearnset", ptr_h))
    learnsets = dict(re.findall(
        r"static const u16 s([A-Za-z0-9]+)LevelUpLearnset\[\] = \{([\s\S]*?)\};", learn))
    offsets = [0]
    packed: list[int] = []
    for species in range(387):
        if species:
            name = national[species]
            row = learnsets.get(pointers.get(name, ""))
            if row is None:
                raise ValueError(f"Missing Emerald learnset for National #{species} ({name})")
            moves = re.findall(r"LEVEL_UP_MOVE\(\s*(\d+),\s*MOVE_([A-Z0-9_]+)\s*\)", row)
            if not moves or len(moves) != row.count("LEVEL_UP_MOVE("):
                raise ValueError(f"Incomplete learnset parsing for {name}")
            for level_str, move_name in moves:
                level = int(level_str)
                move = move_ids.get(move_name, -1)
                if not (1 <= level <= 100 and 1 <= move <= 354):
                    raise ValueError(f"Invalid level or move for {name}: {level}/{move_name}")
                packed.append((level << 9) | move)
        offsets.append(len(packed))
    if len(offsets) != 388 or len(packed) > 65535:
        raise ValueError("Generated table bounds exceeded")
    ps = list(SOURCES.values())
    return (
        "// GENERATED by tools/gen_legality_gen3_emerald_levelup.py (pinned pret source).\n"
        f"// pret/pokeemerald @ {REV}\n"
        f"// pokedex {ps[0]}; moves {ps[1]}\n"
        f"// level-up {ps[2]}; pointers {ps[3]}\n"
        "// National Dex species 1..386; packed (level << 9) | moveId, moveId <=354.\n"
        "// POSITIVE level-up method evidence only; absence is not proof of illegality.\n"
        "inline constexpr std::array<uint16_t,388> kEmeraldLevelOffsets{{\n" +
        fmt(offsets) + "}};\n" +
        f"inline constexpr std::array<uint16_t,{len(packed)}> kEmeraldPackedLevelMoves{{{{\n" +
        fmt(packed) + "}};\n"
    )

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated output without changing it")
    parser.add_argument("--source-root", type=Path, help="Offline checkout of the exact pinned pret revision")
    args = parser.parse_args()
    data = render(args.source_root)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != data:
            raise SystemExit("Emerald level-up data is stale; rerun its pinned generator")
        print("Pinned Emerald level-up evidence: up to date")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(data, encoding="utf-8")
        print(f"Generated {OUT} ({len(data)} bytes)")

if __name__ == "__main__":
    main()
