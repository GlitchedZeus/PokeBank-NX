#!/usr/bin/env python3
"""Render paired Gen V Global Link metadata from the pinned official source export.
No field in this catalog authenticates an individual receipt. Unsupported claims
remain Incomplete. --check compares every emitted byte and the pairing report.
Re-export using global_link_oracle at PKHeX26.10.18 (bfe89c74...).
"""
import argparse,hashlib,json,pathlib,re
ROOT=pathlib.Path(__file__).resolve().parents[2]
PIN='bfe89c74a3f5265805e364b79bc04ad38ebbc5ea'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
source=ROOT/'docs/legality/hardening-20261027/GLOBAL_LINK_CATALOG.json'
rows=json.loads(source.read_text())
assert len(rows)==774
raw=(ROOT/'src/Legality/Gen5LegalityData.cpp').read_text()
block=re.search(r'const Static5 kStatics\[\] = \{(.*?)\n\};',raw,re.S)[1]
native=[[int(v.strip().rstrip('uUlL'),0) for v in row.split(',')] for row in re.findall(r'\{([^{}]+)\}',block)]
assert len(native)==890 and all(len(r)==14 for r in native)
def key(r):return (r['species'],r['form'],r['level'],r['gender'],r['ability'],r['move'])
def nk(r):return (r[0],r[1],r[2],r[7],r[6],r[12])
covered={}
for r in native:
 if r[10]==3:covered[nk(r)]=covered.get(nk(r),0)|r[5]
pairs=[]
for i,r in enumerate(native):
 if r[10]!=3:continue
 assert (r[3],r[4],r[8],r[9],r[11],r[13])==(0,0,1,0,-1,0),('noncanonical Entree',i)
 matches=[n for n,x in enumerate(rows) if key(x)==nk(r) and x['versions']&r[5]]
 assert matches,('unpaired frozen Entree',i)
 pairs.append({'native_index':i,'release_rows':matches})
extras={}
for r in rows:
 assert 1<=r['species']<=649 and 0<r['versions']<16 and r['languages'] in (1,2,3,4,5,6,7)
 missing=r['versions']&~covered.get(key(r),0)
 if missing:extras[key(r)]=extras.get(key(r),0)|missing
h='''// GENERATED by tools/legality_completion/global_link_catalog.py; do not edit.
// PKHeX26.10.18 @ bfe89c74a3f5265805e364b79bc04ad38ebbc5ea (GPL-3.0).
// Catalog recipient claims are not authenticated individual distribution receipts.
#pragma once
#include "Legality/Gen5LegalityData.h"
#include <cstdint>
namespace Legality::Gen5GlobalLink {
struct Claim { uint16_t species; uint8_t form,level; int8_t gender,ability; uint8_t versions; uint16_t move; uint8_t languages; };
inline constexpr Claim kClaims[] = {
'''
for r in rows:h+='    {'+', '.join(str(r[k]) for k in ('species','form','level','gender','ability','versions','move','languages'))+'},\n'
h+='};\ninline constexpr Gen5Data::Static5 kAdditionalEntree[] = {\n'
for (s,f,l,g,ability,move),versions in sorted(extras.items()):h+=f'    {{{s}, {f}, {l}, 75, 0, {versions}, {ability}, {g}, 1, 0, 3, -1, {move}, 0}},\n'
h+='''};
// Every claim is paired by its complete represented encounter identity, never
// by species, a filename, or promotion name alone. Supported alternatives win.
inline bool supports(const Gen5Data::Static5& encounter, uint8_t version, uint8_t language) noexcept {
    if(encounter.kind!=3 || (encounter.location!=0 && encounter.location!=75) || encounter.eggLocation!=0 ||
       encounter.shiny!=1 || encounter.ball!=0 || encounter.nature!=-1 || encounter.pid!=0)return false;
    if(version<20 || version>23)return false;
    const uint8_t game=static_cast<uint8_t>(1u<<(version-20));
    const uint8_t recipient=language==1?1:language==8?2:
        ((language>=2 && language<=5) || language==7)?4:0;
    if(!recipient)return false;
    for(const auto& c:kClaims)
        if(c.species==encounter.species && c.form==encounter.form && c.level==encounter.level &&
           c.gender==encounter.gender && c.ability==encounter.ability && c.move==encounter.move &&
           (c.versions&game) && (c.languages&recipient))return true;
    return false;
}
} // namespace Legality::Gen5GlobalLink
'''
report={'release':PIN,'export_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'raw_export_rows':len(rows),'frozen_native_rows':len(native),'paired_frozen_entree_rows':len(pairs),'additional_entree_rows':len(extras),'pairs':pairs,'meaning':'Source-pinned catalog metadata, not original server logs or an authenticated receipt.'}
outputs={ROOT/'include/Legality/Gen5GlobalLinkCatalog.h':h,ROOT/'docs/legality/hardening-20261027/GLOBAL_LINK_PAIRING.json':json.dumps(report,indent=2)+'\n'}
for path,content in outputs.items():
 if a.check:assert path.read_text()==content,str(path)+' differs'
 else:path.write_text(content)
print(f'Global Link: {len(rows)} release rows, {len(pairs)} frozen pairings, {len(extras)} added encounter rows; '+('CHECK PASS' if a.check else 'rendered'))
