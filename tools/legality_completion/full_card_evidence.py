#!/usr/bin/env python3
"""Reproduce released full-card evidence from pinned, hash-verified archive bytes.

The source is a community archive, not authenticated redemption history. No
filename, checksum, or archive category alone can change a Pokemon verdict.
"""
import argparse
import binascii
import hashlib
import json
from pathlib import Path
import subprocess
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "docs/legality/historical-evidence-20261025/FULL_CARD_MANIFEST.json"
TARGET = ROOT / "include/Legality/Gen5FullCardCatalog.h"
PAYLOAD_SHA = "e21cda424637a71245dd845cb33cdb3356cebc2e236fb1d5012fae26ec643eed"


def relation(a, b):
    if a == b:
        return "exact"
    if a[0xAC:0xB0] == bytes(4) and a[:0xAC] == b[:0xAC] and a[0xB0:] == b[0xB0:]:
        return "receipt_date_only"
    return "different"


def build(args):
    manifest = json.loads(MANIFEST.read_text())
    original = args.pgf.read_bytes()
    payloads = original[:709 * 204]
    if len(original) not in (709 * 204, 709 * 205) or hashlib.sha256(payloads).hexdigest() != PAYLOAD_SHA:
        raise ValueError("catalog payload/order differs from the pinned 709-card source")
    pgfs = [payloads[i:i + 204] for i in range(0, len(payloads), 204)]
    rows, observations, paths = [], [], []
    for entry in manifest["files"]:
        relative = Path(entry["path"])
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("unsafe archive path")
        path = args.archive / relative
        if not path.exists():
            if not args.fetch:
                raise ValueError(f"missing archive file: {relative}")
            url = ("https://raw.githubusercontent.com/" + manifest["repository"] + "/" +
                   manifest["revision"] + "/" + urllib.parse.quote(entry["path"]))
            with urllib.request.urlopen(url, timeout=60) as response:
                data = response.read()
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        data = path.read_bytes()
        if len(data) != 720 or len(data) != entry["size"] or hashlib.sha256(data).hexdigest() != entry["sha256"]:
            raise ValueError(f"archive size/SHA256 mismatch: {relative}")
        blob = hashlib.sha1(b"blob 720\0" + data).hexdigest()
        if blob != entry["git_blob_sha1"]:
            raise ValueError(f"Git blob mismatch: {relative}")
        if binascii.crc_hqx(data[:718], 0xFFFF) != int.from_bytes(data[718:], "little"):
            raise ValueError(f"full-card CRC mismatch: {relative}")
        matches = [(i, relation(data[:204], pgf)) for i, pgf in enumerate(pgfs)]
        matches = [(i, kind) for i, kind in matches if kind != "different"]
        flags, language = int.from_bytes(data[206:208], "little"), data[715]
        record = dict(entry, version_flags=flags, language=language, matches=matches)
        observations.append(record)
        paths.append(str(path))
        released = entry["class"] == "released_archive" and entry["path"].startswith("Released/Gen 5/")
        if released:
            if len(matches) != 1 or flags not in (0x30, 0xF0):
                raise ValueError(f"new/ambiguous released-card pairing needs source review: {relative}")
            rows.append((matches[0][0], flags, language, data[:204], entry["sha256"]))
        elif entry["class"] != "unreleased_archive" or not entry["path"].startswith("Unreleased/Gen 5/"):
            raise ValueError(f"unreviewed provenance class: {relative}")
    if len(observations) != 81 or len(rows) != 63:
        raise ValueError("archive inventory changed; re-audit before regenerating")
    text = '''// GENERATED by tools/legality_completion/full_card_evidence.py.
// Community archive templates ONLY; not authenticated distribution or receipt.
// Only the four documented receipt-date bytes may differ from the catalog.
#pragma once
#include "Legality/Gen5FullWonderCard.h"
#include <array>
#include <span>
#include <string_view>
namespace Legality::Gen5Gift {
struct ArchivedFullCard {
    uint16_t catalogIndex, versionFlags;
    uint8_t language;
    std::array<uint8_t,204> payload;
    std::string_view fullSha256;
};
'''
    text += f'inline constexpr std::string_view kFullCardArchiveRevision="{manifest["revision"]}";\n'
    text += f'inline constexpr std::string_view kFullCardCatalogPayloadSha256="{PAYLOAD_SHA}";\n'
    text += f"inline constexpr std::array<ArchivedFullCard,{len(rows)}> kArchivedFullCards={{{{\n"
    for index, flags, language, data, sha in rows:
        text += f"    {{{index},0x{flags:02X},{language},{{{{\n"
        for pos in range(0, len(data), 24):
            text += "        " + ",".join(f"0x{b:02X}" for b in data[pos:pos + 24]) + ",\n"
        text += f'    }}}},"{sha}"}},\n'
    text += '''}};
struct ArchiveMatch {
    size_t templates = 0;
    bool pairedReceivingClaim = false;
    // Even a byte-identical, checksum-valid archived template cannot prove
    // original distributor provenance, date/device eligibility or acquisition.
    constexpr bool authenticatesReceipt() const noexcept { return false; }
};
[[nodiscard]] inline ArchiveMatch archivedFullCardEvidence(size_t index,
    std::span<const uint8_t> pgf,uint8_t game,uint8_t language) noexcept {
    ArchiveMatch result;
    for(const auto& card:kArchivedFullCards) {
        if(card.catalogIndex!=index) continue;
        const auto relation=FullCard::comparePayloads(card.payload,pgf);
        if(relation!=FullCard::PayloadRelation::Exact && relation!=FullCard::PayloadRelation::ReceiptDateOnly) continue;
        ++result.templates;
        // Released archive contains only BW(30) and all-four(F0) masks.
        // Evaluate each original game/language PAIR; never union two cards.
        const bool version=game>=20&&game<=23&&(card.versionFlags==0xF0||game<=21);
        result.pairedReceivingClaim |= version && language==card.language;
    }
    return result;
}
} // namespace Legality::Gen5Gift
'''
    if args.check:
        if TARGET.read_text() != text:
            raise ValueError("generated full-card catalog is stale")
    else:
        TARGET.write_text(text)
    if args.reader:
        subprocess.run([str(args.reader.resolve()), *paths], check=True, cwd=ROOT)
    summary = {"revision": manifest["revision"], "tree": manifest["tree"],
               "full_cards": len(observations), "released_rows": len(rows),
               "catalog_indices": len({row[0] for row in rows}),
               "crc_ccitt_false": "81/81", "authenticated_receipts": 0,
               "files": observations}
    if args.report:
        args.report.write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n")
    print(f"Full-card evidence: {len(observations)} hash/CRC-verified; {len(rows)} released rows; no receipt authentication")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, required=True)
    parser.add_argument("--pgf", type=Path, required=True)
    parser.add_argument("--fetch", action="store_true", help="download absent files only; never repair/overwrite altered evidence")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--reader", type=Path)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    try:
        build(args)
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + "\n")


if __name__ == "__main__":
    main()
