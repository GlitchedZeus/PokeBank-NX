#!/usr/bin/env python3
"""Generate include/Legality/Gen1PretFishingRB.inc: Red/Blue Super Rod rows.

The 1,512-row pret namespace in Gen1OriginalWildFishingStage.h carries the
physical R/B/Y wild tables and all three rods, but its fishing include only
held Yellow's Super Rod table (plus the game-global Old and Good Rods). This
script adds Red/Blue's Super Rod table from the pinned pret/pokered source,
in the same PretSlot form, so the namespace covers every Gen I rod source.

Usage:
    python3 tools/gen_gen1_pret_super_rod_rb.py --pokered /path/to/pokered

Rows are emitted in pokered's order: maps in SuperRodData order, and within a
map the fishing group's level/species pairs in order (physical slot 0..n-1).
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import verify_gb_legality_data as ver  # noqa: E402

POKERED_SHA = "af519899719f0754965776faac0e836a3b906e6d"
SUPER_ROD_BLOB = "20a52a6c6238685704dd1b0e9957a38be67579b9"
OUT = HERE.parent / "include/Legality/Gen1PretFishingRB.inc"


def map_name(const):
    # PALLET_TOWN -> PalletTown, SEAFOAM_ISLANDS_B3F -> SeafoamIslandsB3F (the
    # spelling the existing pret rows use).
    return "".join(p if re.fullmatch(r"B?\d+F", p) else p.capitalize() for p in const.split("_"))


def parse(text, dex):
    maps = re.findall(r"dbw\s+(\w+),\s*\.(Group\d+)", text)
    groups = {}
    for name, body in re.findall(r"\.(Group\d+):\s*\n((?:\s*db[^\n]*\n)+)", text):
        lines = [l.split(";")[0].strip() for l in body.strip().splitlines()]
        count = int(lines[0].split()[1])
        pairs = []
        for line in lines[1:1 + count]:
            level, species = (x.strip() for x in line[2:].split(","))
            pairs.append((int(level), dex[species]))
        if len(pairs) != count:
            sys.exit(f"{name}: expected {count} pairs, found {len(pairs)}")
        groups[name] = pairs
    rows = []
    for const, group in maps:
        for slot, (level, species) in enumerate(groups[group]):
            rows.append((map_name(const), slot, species, level))
    return maps, rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--pokered", required=True, type=Path)
    args = ap.parse_args()
    src = args.pokered / "data/wild/super_rod.asm"
    head = subprocess.check_output(["git", "-C", str(args.pokered), "rev-parse", "HEAD"], text=True).strip()
    blob = subprocess.check_output(["git", "-C", str(args.pokered), "hash-object", str(src)], text=True).strip()
    if head != POKERED_SHA or blob != SUPER_ROD_BLOB:
        sys.exit(f"pokered must be {POKERED_SHA} with super_rod.asm blob {SUPER_ROD_BLOB}; got {head} / {blob}")
    pret = ver.Pret(args.pokered)
    maps, rows = parse(src.read_text(), pret.dex)

    # Values that are not in question.
    assert len(maps) == 33, len(maps)
    assert rows[0] == ("PalletTown", 0, 72, 15) and rows[1] == ("PalletTown", 1, 60, 15), rows[:2]  # Tentacool, Poliwag
    assert ("CeruleanCave1F", 3, 117, 23) in rows  # Seadra
    assert len(rows) == 109, len(rows)

    out = ["// SPDX-License-Identifier: AGPL-3.0-or-later\n",
           "// GENERATED by tools/gen_gen1_pret_super_rod_rb.py -- do not edit by hand.\n",
           f"// Red/Blue source pret/pokered@{POKERED_SHA}\n",
           f"// data/wild/super_rod.asm blob {SUPER_ROD_BLOB}\n",
           "// Same maps and level/species pairs in Red and Blue (gameMask 3); slot = order in the fishing group.\n",
           f"inline constexpr std::array<PretSlot, {len(rows)}> kPretFishingRB{{{{\n"]
    for name, slot, species, level in rows:
        out.append(f' {{3,"{name}",Method::SuperRod,{slot},{species},{level},0}},\n')
    out.append("}};\n")
    OUT.write_text("".join(out))
    print(f"wrote {OUT.relative_to(HERE.parent)}: {len(rows)} Red/Blue Super Rod rows from {len(maps)} maps")


if __name__ == "__main__":
    main()
