#!/usr/bin/env python3
"""Regenerate include/UI/NunitoMetrics.h: horizontal advances of the app's UI font.

Source (pinned): google/fonts 47d54ca1ebb14fd864695f1d39dc734f39017c33
ofl/nunito/Nunito[wght].ttf -- the same file the Makefile downloads to romfs/fonts/Nunito.ttf
(SHA-256 bb55a5ca5c2042335b3991af27c4d0705d0ef41cac6164ac737fd8f2a1e85207).

NanoVG rasterises with stb_truetype, which reads the default instance's `hmtx` advances (it does
not apply variation deltas) and only the legacy `kern` table, so these advances are what the app
draws. Kerning is ignored here: it only ever narrows a run, so widths computed from this table
are an upper bound, which is what layout checks need.

No third-party Python modules: cmap format 4 / hmtx / hhea / head are parsed directly.
"""
from __future__ import annotations

import hashlib
import pathlib
import struct
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "include" / "UI" / "NunitoMetrics.h"
COMMIT = "47d54ca1ebb14fd864695f1d39dc734f39017c33"
URL = f"https://raw.githubusercontent.com/google/fonts/{COMMIT}/ofl/nunito/Nunito%5Bwght%5D.ttf"
SHA256 = "bb55a5ca5c2042335b3991af27c4d0705d0ef41cac6164ac737fd8f2a1e85207"


def tables(data: bytes) -> dict[str, bytes]:
    count = struct.unpack(">H", data[4:6])[0]
    out = {}
    for i in range(count):
        tag, _, off, length = struct.unpack(">4sIII", data[12 + 16 * i:28 + 16 * i])
        out[tag.decode()] = data[off:off + length]
    return out


def cmap4(cmap: bytes) -> dict[int, int]:
    n = struct.unpack(">H", cmap[2:4])[0]
    for i in range(n):
        platform, encoding, off = struct.unpack(">HHI", cmap[4 + 8 * i:12 + 8 * i])
        if platform == 3 and encoding == 1 and struct.unpack(">H", cmap[off:off + 2])[0] == 4:
            sub = cmap[off:]
            segs = struct.unpack(">H", sub[6:8])[0] // 2
            ends = struct.unpack(f">{segs}H", sub[14:14 + 2 * segs])
            base = 16 + 2 * segs
            starts = struct.unpack(f">{segs}H", sub[base:base + 2 * segs])
            deltas = struct.unpack(f">{segs}h", sub[base + 2 * segs:base + 4 * segs])
            ro_at = base + 4 * segs
            ranges = struct.unpack(f">{segs}H", sub[ro_at:ro_at + 2 * segs])
            glyphs = {}
            for s in range(segs):
                for c in range(starts[s], ends[s] + 1):
                    if c == 0xFFFF:
                        continue
                    if ranges[s] == 0:
                        g = (c + deltas[s]) & 0xFFFF
                    else:
                        at = ro_at + 2 * s + ranges[s] + 2 * (c - starts[s])
                        g = struct.unpack(">H", sub[at:at + 2])[0]
                        g = (g + deltas[s]) & 0xFFFF if g else 0
                    glyphs[c] = g
            return glyphs
    raise SystemExit("no Windows Unicode BMP cmap")


def main() -> None:
    with urllib.request.urlopen(URL) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    assert digest == SHA256, digest
    t = tables(data)
    units = struct.unpack(">H", t["head"][18:20])[0]
    metrics = struct.unpack(">H", t["hhea"][34:36])[0]
    hmtx = t["hmtx"]
    advance = [struct.unpack(">H", hmtx[4 * i:4 * i + 2])[0] for i in range(metrics)]
    glyphs = cmap4(t["cmap"])

    def adv(code: int) -> int:
        g = glyphs.get(code, 0)
        return advance[min(g, metrics - 1)]

    ascii_adv = [adv(c) for c in range(32, 127)]
    # Every Latin-1 / Latin Extended-A letter the UI can show (accented names, "Pokémon").
    wide = max(adv(c) for c in list(range(32, 127)) + list(range(0xA0, 0x180)) if c in glyphs)
    lines = [
        "#pragma once",
        "",
        "// NunitoMetrics.h - horizontal advances of the UI font (Nunito, default instance).",
        "// AUTO-GENERATED by tools/gen_nunito_metrics.py. DO NOT EDIT BY HAND.",
        f"// Source: google/fonts {COMMIT} ofl/nunito/Nunito[wght].ttf",
        f"// (SHA-256 {SHA256}),",
        "// the file the Makefile bundles as romfs:/fonts/Nunito.ttf. Advances are in font units;",
        "// kerning is ignored, so a width from this table is an upper bound of the drawn width.",
        "",
        "#include <cstdint>",
        "",
        "namespace PokeBank::UIModel::NunitoMetrics {",
        "",
        f"inline constexpr int kUnitsPerEm = {units};",
        "// Widest advance among ASCII, Latin-1 Supplement and Latin Extended-A; used for any other",
        "// code point (symbol fallback fonts, accented letters) so estimates never under-count.",
        f"inline constexpr int kWidestAdvance = {wide};",
        "// Advance of U+0020..U+007E.",
        "inline constexpr uint16_t kAsciiAdvance[95] = {",
    ]
    for i in range(0, 95, 16):
        lines.append("    " + " ".join(f"{a}," for a in ascii_adv[i:i + 16]))
    lines += ["};", "", "} // namespace PokeBank::UIModel::NunitoMetrics", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
