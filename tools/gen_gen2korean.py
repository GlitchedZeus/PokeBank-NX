#!/usr/bin/env python3
"""Generate Korean character metadata from pinned GPL-3.0-or-later PKHeX.
Used under GPLv3 section13 with the project's AGPLv3. No ROM/assets imported.
"""
import argparse,hashlib,pathlib,re,subprocess
PIN='6501f0ab46e8f8ca048539dbaf8cae8cb104e722'
p=argparse.ArgumentParser();p.add_argument('pkhex',type=pathlib.Path);p.add_argument('output',type=pathlib.Path);a=p.parse_args()
if subprocess.check_output(['git','-C',str(a.pkhex),'rev-parse','HEAD'],text=True).strip()!=PIN:raise SystemExit('PKHeX pin mismatch')
source=a.pkhex/'PKHeX.Core/PKM/Strings/StringConverter2KOR.cs';s=source.read_text();rows=[]
for table in ['Table0']+['Table'+c for c in '123456789AB']:
 body=s.split('ReadOnlySpan<char> '+table+' =>',1)[1].split('[',1)[1].split('];',1)[0];body=re.sub(r'//[^\n]*','',body)
 cells=[ord(quoted) if quoted else (0x23CE if named=='RET' else 0) for quoted,named in re.findall(r"'([^'])'|\b(NULL|NUL|RET)\b",body)]
 if not cells or len(cells)>256:raise SystemExit('Unexpected table size '+table)
 cells += [0]*(256-len(cells));rows.append(cells)
lines=['// GENERATED by tools/gen_gen2korean.py; do not edit.', '// SPDX-License-Identifier: GPL-3.0-or-later', '// kwsch/PKHeX@'+PIN+' PKHeX.Core/PKM/Strings/StringConverter2KOR.cs', '// Source SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest(), '// Character mapping data used under GPLv3 section13 with this AGPLv3 project.', '#pragma once','#include <array>','#include <cstdint>','namespace Utils {','inline constexpr std::array<std::array<char16_t,256>,12> Gen2KoreanTable{{']
for row in rows:
 lines.append('    {{')
 for i in range(0,256,16):lines.append('        '+', '.join(f'0x{v:04X}' for v in row[i:i+16])+',')
 lines.append('    }},')
lines+=['}};','} // namespace Utils',''];a.output.write_text('\n'.join(lines))
