#!/usr/bin/env python3
"""Generate source-pinned modern filter additions as uncertainty, not native negatives."""
import argparse,hashlib
from pathlib import Path
PINS=('002dc2fbd0d01cc2f346193207c234a792a1ad480cdeda92c105ebb021fbe22e','3f12311c70f766da5e62e63cd4a97787a0cca568366bcd8b825a3d166e925057')
def main():
 p=argparse.ArgumentParser();p.add_argument('old',type=Path);p.add_argument('latest',type=Path);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
 for x,h in zip((a.old,a.latest),PINS):
  assert hashlib.sha256(x.read_bytes()).hexdigest()==h,(x,'source pin mismatch')
 old=set(a.old.read_text(encoding='utf-8-sig').splitlines());new=a.latest.read_text(encoding='utf-8-sig').splitlines();added=[s for s in new if s not in old];assert len(added)==205
 def lit(s):
  return 'u"'+''.join('\\u%04x'%ord(c) if ord(c)>126 else '\\\\' if c=='\\' else '\\"' if c=='"' else c for c in s)+'"'
 a.output.write_text('// Generated by tools/gen_legality_gen5_filter_uncertainty.py.\n// Baseline6501 and release26.10.18 BFE original resource SHA256 pins are in the generator.\n// These205 additions are modern lookback restrictions, not proven original-game impossibilities.\n#pragma once\nnamespace Legality::Gen5Text {\ninline constexpr const char16_t* kUnverifiedLookbackPatterns[] = {\n'+''.join('    '+lit(s)+',\n' for s in added)+'};\n}\n')
if __name__=='__main__':main()
