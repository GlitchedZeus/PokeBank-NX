#!/usr/bin/env python3
"""Generate include/Legality/GBBaseHP.inc: the base HP of species 1-251 for the Gen I/II
party max-HP rule (GBLegality.cpp partyMaxHpProblem).

The values come from the pret disassemblies, independently of PKHeX and of the PKSM port
in Gen2PersonalData.cpp: pokecrystal data/pokemon/base_stats.asm (INCLUDE order, each file
naming its species and dex number) and, for 1-151, pokered data/pokemon/base_stats/*.asm,
which must agree (base HP did not change between the generations).

    tools/gen_gb_base_hp.py --pokered POKERED --pokecrystal POKECRYSTAL [--check]
"""
import argparse
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "include/Legality/GBBaseHP.inc"
STATS = re.compile(r"^\s*db\s+(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*(\d+))?\s*$", re.M)


def crystal(root):
    order = re.findall(r'INCLUDE "(data/pokemon/base_stats/\w+\.asm)"', (root / "data/pokemon/base_stats.asm").read_text())
    hp = {}
    for dex, path in enumerate(order, 1):
        text = (root / path).read_text()
        number = re.search(r"^\s*db\s+\w+\s*;\s*(\d+)", text, re.M)
        if not number or int(number[1]) != dex:
            sys.exit(f"{path}: expected dex {dex}")
        hp[dex] = int(STATS.search(text)[1])
    if sorted(hp) != list(range(1, 252)):
        sys.exit("pokecrystal: expected species 1-251")
    return hp


def red(root):
    # constants/pokedex_constants.asm: const_def 1, then one "const DEX_X" per species.
    names = re.findall(r"^\s*const\s+(DEX_\w+)", (root / "constants/pokedex_constants.asm").read_text(), re.M)
    dex = {name: i for i, name in enumerate(names, 1)}
    hp = {}
    for path in (root / "data/pokemon/base_stats").glob("*.asm"):
        text = path.read_text()
        number = re.search(r"^\s*db\s+(DEX_\w+)", text, re.M)
        if number:
            hp[dex[number[1]]] = int(STATS.search(text)[1])
    if sorted(hp) != list(range(1, 152)):
        sys.exit("pokered: expected species 1-151")
    return hp


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pokered", type=Path, required=True)
    ap.add_argument("--pokecrystal", type=Path, required=True)
    ap.add_argument("--check", action="store_true", help="fail when the committed table differs")
    args = ap.parse_args()
    gsc, rby = crystal(args.pokecrystal), red(args.pokered)
    for dex in range(1, 152):
        if gsc[dex] != rby[dex]:
            sys.exit(f"species {dex}: pokered base HP {rby[dex]} != pokecrystal {gsc[dex]}")
    rows = [str(gsc[dex]) for dex in range(1, 252)]
    body = "// Generated by tools/gen_gb_base_hp.py from pret/pokered and pret/pokecrystal; do not edit.\n"
    body += "// Base HP of species 0-251 (0 for the empty species).\n"
    body += "0,\n" + "".join(", ".join(rows[i:i + 16]) + ",\n" for i in range(0, len(rows), 16))
    if args.check:
        if OUT.read_text() != body:
            sys.exit(f"{OUT} is out of date; rerun tools/gen_gb_base_hp.py")
        print("GBBaseHP.inc matches pret")
    else:
        OUT.write_text(body)
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
