#!/usr/bin/env python3
"""Regenerate the Generation III and IV move type / damage-category table.

Sources (pinned, same commits as tools/gen_move_battle_stats5.py):
  * Pokemon Showdown 3a766f2cfb5e51c1e428cfe87d0dba91a8f01640
    data/moves.ts with the data/mods/gen8 -> gen7 -> gen6 -> gen5 -> gen4 (-> gen3)
    inheritance chain - per-generation move type and (Gen IV) damage category.
  * PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722 PKHeX.Core/Moves/MoveInfo3.cs and
    MoveInfo4.cs - base PP. The generator fails unless Showdown's PP agrees with PKHeX
    for every move, so the Showdown chain is verified against an independent source.

Gen I-III have no per-move category: a damaging move's category follows its TYPE
(Normal/Fighting/Flying/Poison/Ground/Rock/Bug/Ghost/Steel physical, the rest special).
The table therefore stores only the Gen III type; the UI derives "Physical (type)" /
"Special (type)" and never presents it as the Gen IV/V per-move split.
"""
from __future__ import annotations
import pathlib, re, urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "include" / "Names" / "MoveTypes34.h"
PKHEX = ("kwsch/PKHeX", "6501f0ab46e8f8ca048539dbaf8cae8cb104e722")
SHOWDOWN = ("smogon/pokemon-showdown", "3a766f2cfb5e51c1e428cfe87d0dba91a8f01640")
CHAIN4 = ["data/moves.ts", "data/mods/gen8/moves.ts", "data/mods/gen7/moves.ts",
          "data/mods/gen6/moves.ts", "data/mods/gen5/moves.ts", "data/mods/gen4/moves.ts"]
CHAIN3 = CHAIN4 + ["data/mods/gen3/moves.ts"]
TYPES = ["Normal", "Fighting", "Flying", "Poison", "Ground", "Rock", "Bug", "Ghost", "Steel",
         "Fire", "Water", "Grass", "Electric", "Psychic", "Ice", "Dragon", "Dark"]
CATEGORY = {"Physical": 0, "Special": 1, "Status": 2}
MAX3, MAX4 = 354, 467
NO_TYPE = 255  # Showdown "???" (Curse in Gen II-IV)

def fetch(repo, ref, path):
    with urllib.request.urlopen(f"https://raw.githubusercontent.com/{repo}/{ref}/{path}") as r:
        return r.read().decode()

FIELD = re.compile(r'^\t\t(num|category|type|pp): ("[^"]*"|\w+),$', re.M)

def showdown_entries(text):
    out = {}
    for m in re.finditer(r'^\t"?([a-z0-9]+)"?: \{\n(.*?)^\t\},$', text, re.M | re.S):
        out[m.group(1)] = {k: v.strip('"') for k, v in FIELD.findall(m.group(2) + "\n")}
    return out

def merged(chain, cache):
    result = {}
    for path in chain:
        if path not in cache:
            cache[path] = showdown_entries(fetch(*SHOWDOWN, path))
        for key, fields in cache[path].items():
            result.setdefault(key, {}).update(fields)
    by_num = {}
    for key, fields in result.items():
        # hiddenpowerbug .. hiddenpowerwater share num 237; only the base move is the record.
        if key.startswith("hiddenpower") and key != "hiddenpower":
            continue
        if "num" in fields and int(fields["num"]) > 0:
            by_num[int(fields["num"])] = fields
    return by_num

def pkhex_pp(gen):
    text = fetch(*PKHEX, f"PKHeX.Core/Moves/MoveInfo{gen}.cs")
    m = re.search(r"PP\s*=>\s*\[(.*?)\];", text, re.S)
    return [int(v) for v in re.findall(r"\d+", m.group(1))]

def type_id(name):
    return NO_TYPE if name == "???" else TYPES.index(name)

def main():
    cache = {}
    g3, g4 = merged(CHAIN3, cache), merged(CHAIN4, cache)
    pp3, pp4 = pkhex_pp(3), pkhex_pp(4)
    assert len(pp3) == MAX3 + 1 and len(pp4) == MAX4 + 1, (len(pp3), len(pp4))
    rows3, rows4 = [NO_TYPE], [(NO_TYPE, 2)]
    for move in range(1, MAX3 + 1):
        f = g3[move]
        assert int(f["pp"]) == pp3[move], ("gen3 pp", move, f["pp"], pp3[move])
        rows3.append(type_id(f["type"]))
    for move in range(1, MAX4 + 1):
        f = g4[move]
        assert int(f["pp"]) == pp4[move], ("gen4 pp", move, f["pp"], pp4[move])
        rows4.append((type_id(f["type"]), CATEGORY[f["category"]]))
    out = [
        "/**",
        " * MoveTypes34.h - Generation III move types and Generation IV move type + category.",
        " * AUTO-GENERATED by tools/gen_move_types34.py. DO NOT EDIT BY HAND.",
        f" * Type / category: Pokemon Showdown {SHOWDOWN[1]} data/moves.ts with the",
        " * gen8 -> gen7 -> gen6 -> gen5 -> gen4 (-> gen3) mod chain. Base PP of every move is",
        f" * cross-checked against PKHeX {PKHEX[1]} MoveInfo3.cs / MoveInfo4.cs.",
        " * Type uses the PKHeX order (0 Normal .. 16 Dark); 255 = the \"???\" type (Curse).",
        " * Gen III has no per-move category (it follows the type); see moveCategoryForType3.",
        " * Move data only: says nothing about learnability.",
        " */",
        "#ifndef NAMES_MOVE_TYPES34_H",
        "#define NAMES_MOVE_TYPES34_H",
        "#include <array>",
        "#include <cstdint>",
        "namespace Names {",
        "inline constexpr uint8_t kMoveTypeNone34 = 255;",
        f"inline constexpr std::array<uint8_t, {len(rows3)}> kMoveType3{{{{",
    ]
    for i in range(0, len(rows3), 24):
        out.append("    " + " ".join("%d," % r for r in rows3[i:i + 24]))
    out += [
        "}};",
        "struct MoveTypeCategory4 { uint8_t type = 255; uint8_t category = 2; };",
        f"inline constexpr std::array<MoveTypeCategory4, {len(rows4)}> kMoveTypeCategory4{{{{",
    ]
    for i in range(0, len(rows4), 12):
        out.append("    " + " ".join("{%d,%d}," % r for r in rows4[i:i + 12]))
    out += [
        "}};",
        "// Gen I-III physical/special follows the move's type (Bulbapedia \"Damage category\";",
        "// Showdown sim/dex-moves.ts gen<=3 category-by-type rule). 0 Physical, 1 Special.",
        "constexpr uint8_t moveCategoryForType3(uint8_t type) noexcept {",
        "    return type <= 8 ? 0 : type <= 16 ? 1 : 2;",
        "}",
        "} // namespace Names",
        "#endif",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")

if __name__ == "__main__":
    main()
