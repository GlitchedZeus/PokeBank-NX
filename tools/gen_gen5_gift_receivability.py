#!/usr/bin/env python3
"""Bind newer PGF receiving metadata to byte-identical baseline payloads.

GPL-3.0 PKHeX inputs are combined under GPL section 13 with this AGPL project.
The catalog metadata is not independent authentication of a distribution.
"""
import argparse
import hashlib
from pathlib import Path

ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument("--baseline", type=Path, required=True)
ap.add_argument("--current", type=Path, required=True)
ap.add_argument("--check", action="store_true")
args = ap.parse_args()
relative = "PKHeX.Core/Resources/legality/mgdb/pgf.pkl"
old = (args.baseline / relative).read_bytes()
new = (args.current / relative).read_bytes()
if len(old) % 204 or len(new) != len(old) + len(old) // 204 or new[:len(old)] != old:
    raise SystemExit("PGF payloads or ordering changed: metadata alignment requires a new audit")
metadata = new[len(old):]
if any((v >> 4) not in (1, 2, 3, 4, 5, 7, 8) or not (v & 15) for v in metadata):
    raise SystemExit("unexpected receiving-language/version metadata")
text = """// GENERATED by tools/gen_gen5_gift_receivability.py; GPL-3.0 inputs, AGPL section 13.
// PKHeX baseline 6501f0ab46e8f8ca048539dbaf8cae8cb104e722.
// PKHeX receiving metadata 6042efa241a9925ce57e645329ea7f976deabdd3.
// Identical payload bytes are required; this is catalog evidence, not historical authentication.
#pragma once
#include <array>
#include <cstdint>
namespace Legality::Gen5Gift {
"""
for label, data in (("Baseline", old), ("Current", new)):
    text += f'inline constexpr char k{label}Sha256[] = "{hashlib.sha256(data).hexdigest()}";\n'
text += f"inline constexpr std::array<uint8_t,{len(metadata)}> kReceiving = {{\n"
for at in range(0, len(metadata), 24):
    text += "    " + ",".join(f"0x{v:02X}" for v in metadata[at:at+24]) + ",\n"
text += """};
constexpr bool permits(size_t index, uint8_t version, uint8_t language) noexcept {
    if(index>=kReceiving.size()||version<20||version>23)return false;
    const auto metadata=kReceiving[index];
    return (metadata&15)&(1u<<(version-20)) && (metadata>>4)==language;
}
} // namespace Legality::Gen5Gift
"""
text = text.replace("#include <array>", "#include <array>\n#include <cstddef>")
target = Path(__file__).resolve().parents[1] / "include/Legality/Gen5GiftReceivability.h"
if args.check:
    if target.read_text() != text:
        raise SystemExit("receiving metadata is stale")
else:
    target.write_text(text)
