#!/usr/bin/env python3
"""Regenerate include/Integration/Gen5/Gen5PersonalTypes.h.

Type1/Type2 (PersonalInfo5BW/5B2W2 bytes 0x06/0x07, PKHeX type order) for every
row of the same PKHeX personal blobs Gen5PersonalData.h is generated from:
  PKHeX 6501f0ab46e8f8ca048539dbaf8cae8cb104e722
  PKHeX.Core/Resources/byte/personal/personal_bw   (blob de1a0654, 60-byte rows)
  PKHeX.Core/Resources/byte/personal/personal_b2w2 (blob 9236ad13, 76-byte rows)
Row indices match NativePersonalBW / NativePersonalB2W2 exactly.
"""
import hashlib, pathlib, urllib.request
ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "include" / "Integration" / "Gen5" / "Gen5PersonalTypes.h"
REF = "6501f0ab46e8f8ca048539dbaf8cae8cb104e722"
BLOBS = {"BW": ("personal_bw", 60, "de1a0654e8540a5c7e5c8b5e6448db50bb6d8c55"),
         "B2W2": ("personal_b2w2", 76, "9236ad139126af222e915650dbda70d6df897399")}

def fetch(name):
    url = f"https://raw.githubusercontent.com/kwsch/PKHeX/{REF}/PKHeX.Core/Resources/byte/personal/{name}"
    with urllib.request.urlopen(url) as r:
        return r.read()

def main():
    out = ["// AUTO-GENERATED by tools/gen_gen5_personal_types.py. DO NOT EDIT BY HAND.",
           f"// PKHeX {REF} personal_bw / personal_b2w2, bytes 0x06/0x07 (Type1/Type2,",
           "// PKHeX type order 0 Normal .. 16 Dark). Rows align with Gen5PersonalData.h.",
           "#ifndef POKEBANK_GEN5_PERSONAL_TYPES_H", "#define POKEBANK_GEN5_PERSONAL_TYPES_H",
           "#include \"Integration/Gen5/Gen5PersonalData.h\"", "#include <array>", "#include <cstdint>",
           "namespace PokeVault::Integration::Gen5 {"]
    for key, (name, size, blob) in BLOBS.items():
        data = fetch(name)
        assert hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest() == blob, name
        rows = len(data) // size
        pairs = [(data[i * size + 6], data[i * size + 7]) for i in range(rows)]
        out.append(f"inline constexpr std::array<std::array<uint8_t,2>,{rows}> NativePersonalTypes{key}{{{{")
        for i in range(0, rows, 12):
            out.append("    " + " ".join("{{%d,%d}}," % p for p in pairs[i:i + 12]))
        out.append("}};")
        out.append(f"static_assert(NativePersonalTypes{key}.size() == NativePersonal{key}.size());")
    out += ["// Types of the exact native species/form row (personal5 index rules).",
            "constexpr std::array<uint8_t,2> personalTypes5(uint32_t species,uint32_t form,bool b2w2) noexcept {",
            "    const auto selected=personal5(species,form,b2w2);",
            "    if(selected.info==nullptr)return {0xFF,0xFF};",
            "    if(b2w2)return NativePersonalTypesB2W2[static_cast<size_t>(selected.info-NativePersonalB2W2.data())];",
            "    return NativePersonalTypesBW[static_cast<size_t>(selected.info-NativePersonalBW.data())];",
            "}",
            "static_assert(personalTypes5(1,0,false)[0]==11 && personalTypes5(1,0,false)[1]==3); // Bulbasaur Grass/Poison",
            "static_assert(personalTypes5(25,0,true)[0]==12 && personalTypes5(25,0,true)[1]==12); // Pikachu Electric",
            "} // namespace PokeVault::Integration::Gen5", "#endif", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")

if __name__ == "__main__":
    main()
