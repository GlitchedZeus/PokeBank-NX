#pragma once

// Native default moveset for a Generation I-V Pokemon of a given species, form and level
// (R2-BUG-004): what the game itself gives a wild or freshly created Pokemon.
//
// Algorithm, identical in every generation once Gen I's base moves are seeded:
//   Gen I    pret pokered / pokeyellow engine/pokemon/evos_moves.asm WriteMonMoves: start
//            from the base-stats "level 1 learnset", then walk evos_moves in order;
//   Gen II   pret pokecrystal engine/pokemon/move_mon.asm FillMoves over evos_attacks;
//   Gen III  pret pokeemerald src/pokemon.c GiveMonInitialMoveset;
//   Gen IV/V PKHeX 6501f0ab Learnset.SetEncounterMoves (the same rule on lvlmove_*).
// For each level-up entry at or below the level, in table order: skip it when the move is
// already held; otherwise fill the next empty slot, or, with all four full, drop the first
// (oldest) move and append. The result is the last four distinct moves, in learn order.
//
// Data: include/Pokemon/LevelUpLearnsets15Data.inc, generated by tools/gen_levelup_learnsets15.py
// from pinned pret disassemblies (Gen I-III) and PKHeX lvlmove resources (Gen IV/V), with
// Gen I-III cross-checked against PKHeX. When a table has no row for the species the result
// is `known == false` with every slot empty: callers clear the moves, never keep the old ones.

#include <algorithm>
#include <array>
#include <cstdint>
#include <iterator>
#include <span>

namespace PokeBank::Moves {

// One table per distinct native learnset source; 13 tables cover the 20 Gen I-V games.
enum class LevelUpTable15 : uint8_t {
    RedBlue, Yellow, GoldSilver, Crystal, RubySapphire, Emerald, FireRed, LeafGreen,
    DiamondPearl, Platinum, HeartGoldSoulSilver, BlackWhite, Black2White2, Count
};

struct LevelUpIndex15 {
    uint8_t table;
    uint16_t species;
    uint8_t form;
    uint16_t start;
    uint8_t count;
};

struct LevelUpMove15 {
    uint8_t level;  // 0 = Gen I base move (applied first)
    uint16_t move;
};

namespace detail {
#include "Pokemon/LevelUpLearnsets15Data.inc"

inline const LevelUpIndex15* findLevelUpRow(LevelUpTable15 table, uint16_t species, uint8_t form) noexcept {
    const auto t = static_cast<uint8_t>(table);
    const auto* begin = std::begin(kLevelUpIndex15);
    const auto* end = std::end(kLevelUpIndex15);
    // Rows are sorted by (table, species, form) by the generator.
    const auto* it = std::lower_bound(begin, end, 0, [&](const LevelUpIndex15& row, int) {
        return row.table < t || (row.table == t && (row.species < species ||
                                                    (row.species == species && row.form < form)));
    });
    if (it != end && it->table == t && it->species == species && it->form == form) return it;
    return nullptr;
}
} // namespace detail

// Gen III origin byte (PK3 "Origins" version: 1 Sapphire, 2 Ruby, 3 Emerald, 4 FireRed,
// 5 LeafGreen; pokeemerald VERSION_*). Count when not a Gen III game.
[[nodiscard]] constexpr LevelUpTable15 levelUpTableForGen3Version(uint8_t version) noexcept {
    switch (version) {
        case 1: case 2: return LevelUpTable15::RubySapphire;
        case 3: return LevelUpTable15::Emerald;
        case 4: return LevelUpTable15::FireRed;
        case 5: return LevelUpTable15::LeafGreen;
        default: return LevelUpTable15::Count;
    }
}
// Gen IV / V origin byte (PKHeX GameVersion: 7 HG, 8 SS, 10 D, 11 P, 12 Pt, 20 W, 21 B,
// 22 W2, 23 B2). Count when not a Gen IV/V game.
[[nodiscard]] constexpr LevelUpTable15 levelUpTableForGen45Version(uint8_t version) noexcept {
    switch (version) {
        case 10: case 11: return LevelUpTable15::DiamondPearl;
        case 12: return LevelUpTable15::Platinum;
        case 7: case 8: return LevelUpTable15::HeartGoldSoulSilver;
        case 20: case 21: return LevelUpTable15::BlackWhite;
        case 22: case 23: return LevelUpTable15::Black2White2;
        default: return LevelUpTable15::Count;
    }
}
[[nodiscard]] constexpr LevelUpTable15 levelUpTableGen1(bool yellow) noexcept {
    return yellow ? LevelUpTable15::Yellow : LevelUpTable15::RedBlue;
}
[[nodiscard]] constexpr LevelUpTable15 levelUpTableGen2(bool crystal) noexcept {
    return crystal ? LevelUpTable15::Crystal : LevelUpTable15::GoldSilver;
}

[[nodiscard]] constexpr LevelUpMove15 decodeLevelUp(uint32_t entry) noexcept {
    return {static_cast<uint8_t>(entry >> 16), static_cast<uint16_t>(entry & 0xFFFFu)};
}

// The table's rows for species/form, in native order. A form without its own row uses the
// species' base form (PKHeX PersonalTable form fallback). Empty when the species is absent.
[[nodiscard]] inline std::span<const uint32_t> levelUpLearnset(LevelUpTable15 table, uint16_t species,
                                                               uint8_t form = 0) noexcept {
    if (table >= LevelUpTable15::Count || species == 0) return {};
    const LevelUpIndex15* row = detail::findLevelUpRow(table, species, form);
    if (!row && form != 0) row = detail::findLevelUpRow(table, species, 0);
    if (!row) return {};
    return std::span<const uint32_t>(detail::kLevelUpPool15 + row->start, row->count);
}

struct DefaultMoves {
    std::array<uint16_t, 4> moves{};  // 0 = empty slot
    uint8_t count = 0;
    bool known = false;               // false: no learnset row, every slot empty
};

[[nodiscard]] inline DefaultMoves defaultMoves(LevelUpTable15 table, uint16_t species, uint8_t form,
                                               uint8_t level) noexcept {
    DefaultMoves out;
    const auto rows = levelUpLearnset(table, species, form);
    if (rows.empty()) return out;
    out.known = true;
    for (const uint32_t entry : rows) {
        const auto [moveLevel, move] = decodeLevelUp(entry);
        if (moveLevel > level || move == 0) continue;
        const auto held = out.moves.begin() + out.count;
        if (std::find(out.moves.begin(), held, move) != held) continue;
        if (out.count < 4) {
            out.moves[out.count++] = move;
        } else {
            std::rotate(out.moves.begin(), out.moves.begin() + 1, out.moves.end());
            out.moves[3] = move;
        }
    }
    return out;
}

} // namespace PokeBank::Moves
