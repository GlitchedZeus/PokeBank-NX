constexpr std::uint16_t moveFor(std::uint8_t game, std::uint16_t species,
                                bool hm, std::uint8_t number) noexcept {
    if((game!=1&&game!=2&&game!=3)||species<1||species>151||
       number<1||number>(hm?5:50))return 0;
    const auto machine=static_cast<std::uint8_t>((hm?50:0)+number);
    const auto allowed=game==3?kYellow[species]:kRB[species];
    return (allowed&(std::uint64_t{1}<<(machine-1)))?kMoves[machine]:0;
}
static_assert(kMoves[24]==85); // TM24 Thunderbolt
static_assert(moveFor(1,25,false,24)==85&&moveFor(3,25,false,24)==85);
static_assert(moveFor(1,25,true,5)==148); // Pikachu original HM05 Flash
static_assert(moveFor(1,132,false,10)==0); // Ditto has no TM10
static_assert(moveFor(1,151,true,5)==148); // Mew HM05 Flash
static_assert(moveFor(3,151,false,50)==164); // Mew TM50 Substitute
